export function getSubstitutionTranslations(exercise: {
  id: string;
  validCombinations?: Array<{ fullSentence?: string; banglaMeaning?: string }>;
  sentenceTranslations?: Array<{ en: string; bn: string }>;
}): SubstitutionSentenceTranslation[] {
  if (!exercise) return [];

  // 1. If explicitly defined in exercise
  if (exercise.sentenceTranslations && exercise.sentenceTranslations.length > 0) {
    return exercise.sentenceTranslations;
  }

  // 2. Lookup in our comprehensive dictionary
  if (exercise.id && SUBSTITUTION_SENTENCE_TRANSLATIONS[exercise.id]) {
    return SUBSTITUTION_SENTENCE_TRANSLATIONS[exercise.id];
  }

  // 3. If validCombinations have banglaMeaning
  if (exercise.validCombinations && exercise.validCombinations.length > 0) {
    const fromCombos = exercise.validCombinations
      .filter((c) => c.fullSentence)
      .map((c) => ({
        en: c.fullSentence || '',
        bn: c.banglaMeaning || 'এই বাক্যের অর্থ উপলব্ধ।',
      }));
    if (fromCombos.length > 0) return fromCombos;
  }

  return [];
}
