// Smart lookup helper with fallback for regular forms
export function getVerbDetail(rawVerb: string): VerbDetail {
  const clean = (rawVerb || '').trim().toLowerCase();
  if (VERB_DICTIONARY[clean]) {
    return VERB_DICTIONARY[clean];
  }

  // Fallback heuristic for any unmapped English verb
  const isEndsWithE = clean.endsWith('e');
  const pastForm = isEndsWithE ? `${clean}d` : `${clean}ed`;
  const ingForm = isEndsWithE ? `${clean.slice(0, -1)}ing` : `${clean}ing`;
  const sForm = clean.endsWith('s') || clean.endsWith('sh') || clean.endsWith('ch') || clean.endsWith('x') || clean.endsWith('o') ? `${clean}es` : `${clean}s`;

  return {
    verb: rawVerb,
    pronunciationBn: rawVerb,
    ipa: `/${rawVerb}/`,
    meaningBn: `ক্রিয়াপদ (${rawVerb})`,
    v1: rawVerb,
    v2: pastForm,
    v2Bn: `${pastForm}`,
    v3: pastForm,
    v3Bn: `${pastForm}`,
    vIng: ingForm,
    vS: sForm,
    exampleSentence: `Understand the right form and tense of "${rawVerb}".`,
  };
}
