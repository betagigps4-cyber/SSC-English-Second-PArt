/**
 * Returns the Bangla translation for a given PunctuationExercise.
 */
export function getPunctuationBanglaMeaning(exercise?: PunctuationExercise | null): string {
  if (!exercise) return '';
  if (exercise.banglaMeaning) return exercise.banglaMeaning;
  if (exercise.banglaTranslation) return exercise.banglaTranslation;
  if (exercise.id && PUNCTUATION_BANGLA_TRANSLATIONS[exercise.id]) {
    return PUNCTUATION_BANGLA_TRANSLATIONS[exercise.id];
  }
  // Try fallback by matching normalized board name
  const normalizedId = (exercise.board || '')
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '');
  for (const [k, v] of Object.entries(PUNCTUATION_BANGLA_TRANSLATIONS)) {
    if (k.includes(normalizedId) || normalizedId.includes(k.replace('punc-', ''))) {
      return v;
    }
  }
  return '';
}
