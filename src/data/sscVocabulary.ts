/**
 * Searches the curated dictionary or generates a contextual result for any SSC word
 */
export function lookupSscWord(query: string): WordLookupResult | null {
  if (!query || !query.trim()) return null;
  const clean = query.trim().toLowerCase();

  // 1. Direct match in curated vocabulary
  if (SSC_CURATED_VOCABULARY[clean]) {
    return SSC_CURATED_VOCABULARY[clean];
  }

  // 2. Check if the query matches a derivative form
  for (const key in SSC_CURATED_VOCABULARY) {
    const entry = SSC_CURATED_VOCABULARY[key];
    if (entry.word.toLowerCase() === clean) return entry;
    if (entry.derivatives?.some((d) => d.form.toLowerCase() === clean)) {
      return entry;
    }
  }

  // 3. Partial or root match
  for (const key in SSC_CURATED_VOCABULARY) {
    if (clean.includes(key) || key.includes(clean)) {
      return SSC_CURATED_VOCABULARY[key];
    }
  }

  return null;
}

